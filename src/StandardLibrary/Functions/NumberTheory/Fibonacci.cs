        public FunctionValue Execute(params FunctionArgument[] args)
        {
            return base.Execute(args, (_args) =>
            {
                var input = _args[0].Value;

                int index = Convert.ToInt32(input);

                if(index <= 0 || index > 140)
                {
                    return FunctionValue.ZERO;
                }

